def parse_beats(raw: str, cast: list[dict[str, Any]],
                kind: str = "", directed: bool = False) -> list[dict[str, Any]]:
    """Строки модели → такты. Всё сомнительное выбрасывается.

    Сцена играется движком, поэтому пропускать сюда «почти правильное» нельзя:
    выдуманное имя означало бы реплику из ниоткуда, выдуманное действие —
    молчаливый отказ движка.

    В мирной сцене разрешён только безобидный набор действий, а квестовый
    персонаж защищён вдвойне: и как исполнитель, и как ЖЕРТВА — иначе пьяная
    драка в таверне похоронила бы сюжетную линию вместе с её хозяином.
    """
    allowed = SAFE_ACTIONS if is_safe(kind, directed) else SCENE_ACTIONS
    by_name = {str(c.get("name") or "").strip().lower(): c for c in cast}

    # Некоторые модели пишут такт СТОЛБИКОМ: имя на своей строке, а остальные
    # поля ниже, каждое со своей «|». Замер на saineko-hydra через кобольд дал
    # ровно это, и разбор возвращал ноль тактов при вполне живых репликах.
    # Склеиваем такие продолжения с предыдущей строкой — форма выравнивается,
    # а строгость к содержанию остаётся прежней.
    lines: list[str] = []
    for ln in (raw or "").splitlines():
        if ln.lstrip().startswith("|") and lines:
            lines[-1] = lines[-1].rstrip() + " " + ln.strip()
        else:
            lines.append(ln)

    beats: list[dict[str, Any]] = []
    for raw_line in lines:
        if raw_line.count("|") < 3:
            continue
        # Модели любят обрамлять имя разметкой: «**Тидрал**», `Тидрал`. Для
        # имени и действия это смертельно — они сверяются по точному совпадению.
        parts = [p.strip().strip("*«»`\"'“”_ ") for p in raw_line.split("|")]
        # Голова строки — номер такта или слово «ТАКТ»; и того и другого может
        # не быть вовсе. Отбрасываем её, только если она пустая по смыслу,
        # иначе съели бы имя говорящего.
        if parts and _HEAD_RE.match(parts[0]):
            parts = parts[1:]
        if len(parts) < 4:
            continue
        who = by_name.get(parts[0].lower())
        if who is None:
            logger.debug("такт мимо состава: %r", parts[0])
            continue
        line = parts[2].strip()
        if not line or line == "-":
            continue
        action = (parts[3] if len(parts) > 3 else "none").strip().lower()
        if action not in allowed:
            action = "none"
        goto = by_name.get(parts[1].strip().lower()) if len(parts) > 1 else None
        target = by_name.get(parts[4].strip().lower()) if len(parts) > 4 else None
        # Квестового не трогаем ни с какой стороны: ни он бьёт, ни его бьют.
        if action not in SAFE_ACTIONS and (who.get("story")
                                           or (target and target.get("story"))):
            action = "none"
        beats.append({
            "id": str(who.get("id") or ""),
            "name": str(who.get("name") or ""),
            "is_male": bool(who.get("is_male", True)),
            "race": str(who.get("race") or ""),
            "walk_to": str(goto.get("id") or "") if goto else "",
            "line": line,
            "action": action,
            "target": str(target.get("id") or "") if target else "",
        })
        if len(beats) >= MAX_BEATS:
            break
    return beats


class SceneAgent:
    """Сцены на несколько человек — по указанию игрока или по воле мира."""

    def __init__(self, config: dict[str, Any]) -> None:
        cfg = (config.get("models") or {}).get("scene_agent") \
            or (config.get("models") or {}).get("d2d_agent") or {}
        self.llm = get_provider(cfg)
        self.model_name = getattr(self.llm, "model", "")
        self._temperature = float(cfg.get("temperature", 0.95))

    async def stage(self, req: dict[str, Any]) -> dict[str, Any]:
        """Поставить сцену. req: kind|order, cast, location, when."""
        cast: list[dict[str, Any]] = list(req.get("cast") or [])
        if len(cast) < 1:
            return {"beats": []}
        names = [str(c.get("name") or "") for c in cast]
        location = str(req.get("location") or "Вварденфелл")
        when = str(req.get("when") or "день")

        order = str(req.get("order") or "").strip()
        kind = str(req.get("kind") or "").strip()
        if order:
            what = ("УКАЗАНИЕ РЕЖИССЁРА (игрок задаёт, что произойдёт — "
                    "исполни его буквально, но живо):\n" + order)
        else:
            info = SCENE_KINDS.get(kind) or SCENE_KINDS["gossip_ring"]
            what = f"ПОВОД: {info['title']}.\n{info['brief']}"

        parts = [
            "СОСТАВ (играть можно ТОЛЬКО этими; имена писать точно так):\n"
            + _cast_block(cast),
            what,
        ]

        # Что у игрока уже сделано. Раньше режиссёр этого не знал вовсе, и
        # ставил сцены про давно закрытые дела: Фаргот при игроке обвинял
        # соседа в краже кольца, которое сам же час назад получил обратно.
        quests = str(req.get("quests") or "").strip()
        if quests:
            parts.append(
                "ЧТО УЖЕ ПРОИЗОШЛО У ЭТИХ ЛЮДЕЙ С ИГРОКОМ:\n" + quests + "\n"
                "Сделанное — позади. НЕ ставь сцену про то, что уже решено: "
                "потерянное найдено, долг отдан, пропажа вернулась. Играть "
                "можно последствия («с тех пор как мне вернули кольцо…»), но "
                "не сам закрытый вопрос."
            )

        # Тайники и секреты. Модель знает лор Морровинда и однажды выдала при
        # игроке чужой тайник — пень за маяком, где Фаргот прячет своё золото,
        # — приписав ему хранение кольца. Так игроку портят находку и заодно
        # путают, чьё это вообще.
        parts.append(
            "ЧУЖИХ ТАЙНИКОВ НЕ ВЫДАВАТЬ. Не называй мест, где кто-то что-то "
            "прячет: ни пней, ни ям, ни половиц. Игрок должен находить такое "
            "сам. Тем более не приписывай тайник одного человека другому."
        )
        # Фарс — отдельный слой поверх повода, а не замена ему.
        if req.get("absurd"):
            parts.append(ABSURD_GUIDE)
            used = [str(x) for x in (req.get("used_jokes") or []) if str(x).strip()]
            if used:
                parts.append("УЖЕ БЫЛО в этом мире, повторять НЕЛЬЗЯ:\n"
                             + "\n".join(f"  - {u}" for u in used[-12:]))
        parts.append(_schema(names))
        user = "\n\n".join(parts)

        resp = await call_with_retry(lambda: self.llm.complete(
            system=_system(location, when, house_rules()),
            messages=[{"role": "user", "content": user}],
            temperature=self._temperature,
            max_tokens=700,
        ))
        log_llm_response("SceneAgent", resp)

        beats = parse_beats(resp.text, cast, kind, directed=bool(order))
        logger.info("SceneAgent | %s%s | состав %d | тактов %d | токенов %d",
                    kind or "указание", " (фарс)" if req.get("absurd") else "",
                    len(cast), len(beats), resp.tokens_in + resp.tokens_out)
        return {"beats": beats, "kind": kind, "order": order,
                "absurd": bool(req.get("absurd")),
                "tokens_used": resp.tokens_in + resp.tokens_out,
                "cost_usd": resp.cost_usd}
