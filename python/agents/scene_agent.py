def is_absurd_roll(humour: int, roll: float) -> bool:
    """Выпал ли фарс на это конкретное событие.

    Ручка задаёт ШАНС, а не тон: событие выходит либо честным, либо клоунадой
    целиком. Постоянный полуабсурд читается как шум и портит оба жанра сразу.
    """
    return roll * 100.0 < max(0, min(100, int(humour)))


def kinds_allowed_for(danger: int, fit: list[str]) -> list[str]:
    """Из поводов, подходящих по обстановке, оставить уместные при этой опасности.

    Мирные доступны всегда — без них при нуле не осталось бы ничего. Злые
    открываются с 40 и дальше просто попадаются чаще: чем выше ручка, тем
    больше раз каждый злой повод кладётся в мешок.
    """
    fit = [k for k in (fit or []) if k in SCENE_KINDS]
    if not fit:
        fit = ["gossip_ring"]
    d = max(0, min(100, int(danger)))
    peaceful = [k for k in fit if SCENE_KINDS[k].get("safe", True)]
    if d < 40:
        return peaceful or fit
    rough = [k for k in fit if not SCENE_KINDS[k].get("safe", True)]
    # 40 -> злой повод в мешке один раз, 100 -> четыре: мирные никуда не
    # деваются, просто перестают быть единственными.
    times = 1 + int((d - 40) / 20)
    return peaceful + rough * times


def is_safe(kind: str, directed: bool = False) -> bool:
    """Мирная ли сцена — то есть можно ли в ней только разговаривать.

    Незнакомый повод считаем мирным: так безопаснее. НО сцена, заданную самим
    игроком, мирной не считаем никогда — он ставит её осознанно и вправе
    получить драку, если её просил. Квестовые персонажи защищены отдельно и
    от этого не зависят.
    """
    if directed:
        return False
    return bool((SCENE_KINDS.get(kind) or {}).get("safe", True))

# Строка такта. Модель почти никогда не повторяет слово «ТАКТ» буквально: в
# живых прогонах она нумерует такты («1 | Тидрал | ...»), а то и начинает
# прямо с имени. Поэтому опознаём такт по СТРУКТУРЕ — поля через «|», — а
# лишнюю голову (номер или слово «ТАКТ») просто отбрасываем.
_HEAD_RE = re.compile(r"^\s*(?:такт\s*)?\d*[.):]?\s*$", re.IGNORECASE)


def _cast_block(cast: list[dict[str, Any]]) -> str:
    lines = []
    for c in cast:
        name = str(c.get("name") or "")
        race = str(c.get("race") or "")
        klass = str(c.get("class") or "")
        fac = str(c.get("faction") or "")
        bits = [b for b in (race, klass, fac) if b]
        lines.append(f"  - {name} ({', '.join(bits) or 'горожанин'})"
                     + ("  [КВЕСТОВЫЙ — только слова, никаких действий]"
                        if c.get("story") else ""))
    return "\n".join(lines)


