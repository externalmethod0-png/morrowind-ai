"""
fates_live.py — калибровка судеб: зацикленной и нелепых.

Проверяем не «тег принялся», а то, что человек ГОВОРИТ, живя своей судьбой.
Зацикленная прогоняется по кругу: город за городом, с накоплением списка тех,
где он уже побывал, — ровно так, как это делает Lua.

Расходует запросы к модели.
Запуск:  venv\\Scripts\\python.exe tests\\fates_live.py
"""

from __future__ import annotations

import asyncio
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "python"))

# Те же строки, что в Lua (FATE_STORY): стенд должен видеть ровно то же, что
# увидит игра, иначе калибровка врёт.
STORY = {
    "ticket": ("обжился было, но всё оказалось не так, как обещали",
               "перебивается кое-как и уже поглядывает на дорогу",
               "снова сидит с протянутой рукой и копит на билет — "
               "теперь-то уж точно в правильный город"),
    "actor": ("прибился к бродячим комедиантам таскать сундуки",
              "вышел на сцену — играет заднюю ногу гуара",
              "играет заднюю ногу гуара так, что и на улице его зовут Ногой"),
    "prophet": ("начал толковать прохожим свой вещий сон",
                "обзавёлся двумя слушателями и чужой мантией не по размеру",
                "основал учение; последователей по-прежнему двое, "
                "и оба должны ему денег"),
    "fisher": ("поклялся поймать ту самую рыбу, что сорвалась",
               "просиживает на мостках с рассвета, рыбы не видит",
               "о рыбе больше не говорит, но с мостков не уходит"),
    "clerk": ("устроился переписчиком в контору",
              "нашёл в бумагах ошибку двадцатилетней давности",
              "ведёт с конторой переписку об этой ошибке; работать некогда"),
    "guard_ic": ("взяли в стражу, дали пост у пустого сарая",
                 "охраняет сарай образцово, внутрь так и не заглядывал",
                 "сарай снесли, пост остался — стоит и охраняет место"),
}


def fate_note(role: str, town: str, days: int, been: list[str]) -> str:
    """Та же записка, что собирает Lua в fateNote()."""
    line = STORY[role]
    stage = min(len(line), 1 + days // 3)
    s = (f"ТВОЯ СУДЬБА ПОСЛЕ ТОГО РАЗГОВОРА: ты в городе {town}, "
         f"прошло дней: {days}. Сейчас ты {line[stage - 1]}.")
    s += (" ОТВЕЧАЙ ПО СУЩЕСТВУ: скажи прямо, чем ты теперь занят и как дошёл "
          "до такого. НЕ НАЧИНАЙ с отговорки и встречного вопроса («какая тебе "
          "разница», «тебе-то что») — про свою жизнь ты рассказываешь охотно, "
          "с первого же слова и по делу. Говори как о деле, а не как о курьёзе: "
          "смешным своё положение ты не считаешь. И держись СВОЕЙ судьбы — "
          "чужих занятий себе не приписывай.")
    if role == "ticket" and stage >= len(line):
        seen = ", ".join(been + [town])
        s += (" ТЫ СНОВА КОПИШЬ НА БИЛЕТ и просишь у собеседника денег на "
              "дорогу — ровно так же, как просил в прошлый раз, и совершенно "
              "серьёзно: вот на этот раз всё точно сложится, потому что "
              "<назови свою причину, каждый раз новую и убедительную>. "
              "КУДА именно — выбери ОДИН город Вварденфелла из этих: Балмора, "
              "Вивек, Альд'рун, Кальдера, Пелагиад, Садрит Мора, Гнисис, "
              "Суран, Эбенгард, Кхуул, Маар Ган, Гнаар Мок, Вос, Хла Оуд. "
              f"НЕЛЬЗЯ называть те, где ты уже пожил и не сложилось: {seen}. "
              "Нельзя и Сиродил с Имперским городом — на них у тебя денег не "
              "хватит никогда. Если из списка не осталось ни одного — скажи, "
              "что понял главное, и просишь на дорогу ДОМОЙ, туда, откуда всё "
              "начиналось. Ты НЕ ПОМНИШЬ этой закономерности и не находишь в "
              "ней ничего странного: каждый раз это первая и единственная "
              "твоя попытка.")
    return s


async def ask(agent, name: str, note: str, town: str, said: str) -> dict:
    return await agent.generate_response({
        "npc_id": "fate_" + name, "npc_name": name, "npc_race": "Imperial",
        "npc_class": "Commoner", "npc_faction": "", "location": town,
        "npc_is_male": True, "npc_disposition": 55,
        "player_input": said, "conversation_history": [],
        "player_context": "время 13:00 (день); игрок: ЖЕНЩИНА, раса dark elf",
        "npc_fate": note,
    }, memory_context=[])


async def main() -> int:
    import yaml

    from agents.lore_agent import LoreAgent
    cfg = yaml.safe_load((ROOT / "python" / "config.yaml").read_text(encoding="utf-8"))
    agent = LoreAgent(cfg)

    print("══ ЗАЦИКЛЕННАЯ СУДЬБА: круг по провинции ══")
    been: list[str] = ["Сейда Нин"]
    town = "Балмора"
    for round_no in range(1, 5):
        note = fate_note("ticket", town, days=9, been=been)
        r = await ask(agent, "Водуниус Нуцциус", note, town,
                      "Погоди… Водуниус? Ты же был в Сейда Нин. Как ты тут оказался?")
        print(f"\n  круг {round_no} — {town} (был в: {', '.join(been)})")
        print(f"    {r['response']}")
        been.append(town)
        town = {"Балмора": "Вивек", "Вивек": "Альд'рун",
                "Альд'рун": "Кальдера"}.get(town, "Сейда Нин")

    print("\n══ НЕЛЕПЫЕ СУДЬБЫ ══")
    for role, name, said in (
        ("actor", "Кресций Кайус", "Ты чего в таком виде? Что с тобой стало?"),
        ("prophet", "Фонус Раций", "Ну, как жизнь на новом месте?"),
        ("fisher", "Тидрал", "Рыбачишь? Клюёт хоть?"),
        ("clerk", "Ловис Ветурий", "Слышал, ты в контору устроился. Как оно?"),
        ("guard_ic", "Севин Дрелас", "О, тебя в стражу взяли? Что охраняешь?"),
    ):
        note = fate_note(role, "Балмора", days=9, been=[])
        r = await ask(agent, name, note, "Балмора", said)
        print(f"\n  [{role}] {name}:")
        print(f"    {r['response']}")
    return 0


if __name__ == "__main__":
    sys.exit(asyncio.run(main()))
